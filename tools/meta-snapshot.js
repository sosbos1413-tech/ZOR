#!/usr/bin/env node
/*
 * teen #20: writes core/meta.js, the "meta" numbers the stats screen shows to players (hero and synergy win rates from
 * AI-vs-AI simulation). Re-run after balance changes:  node tools/meta-snapshot.js [gamesPerHero=1000]
 */
const path = require('path'), cp = require('child_process'), fs = require('fs');
const G = +(process.argv[2] || 1000), root = path.join(__dirname, '..');
const run = (args) => cp.execFileSync(process.execPath, args, { cwd: root, maxBuffer: 1 << 26 }).toString();
const heroes = {}; [1, 2].forEach((s) => run(['tools/bench.js', String(G), String(s), '4']).split('\n').forEach((l) => { const m = l.match(/^(\w+)\s+([\d.]+)%/); if (m) heroes[m[1]] = (heroes[m[1]] || 0) + +m[2] / 2; }));
const syn = {}; [3, 4].forEach((s) => { const out = run(['tools/simulate.js', '1500', String(s)]); const sec = out.split('== synergies')[1].split('==')[0]; sec.split('\n').forEach((l) => { const m = l.match(/^\s+(\w+)\s+picks\s+\d+\s+win\s+([\d.]+)%/); if (m) syn[m[1]] = (syn[m[1]] || 0) + +m[2] / 2; }); });
const r1 = (o) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k, Math.round(v * 10) / 10]));
const out = `/* generated by tools/meta-snapshot.js on ${new Date().toISOString().slice(0, 10)}: AI-vs-AI win rates (hero: ${G} games x2 seeds; synergy: 1500 games x2 seeds) */
(function () { globalThis.AMB = globalThis.AMB || {}; AMB.META = ${JSON.stringify({ date: new Date().toISOString().slice(0, 10), heroes: r1(heroes), synergies: r1(syn) })}; })();
`;
fs.writeFileSync(path.join(root, 'core', 'meta.js'), out); console.log(out);
